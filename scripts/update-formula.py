#!/usr/bin/env python3
"""Generate a stable formula from the exact archives produced by a release."""
import hashlib
from pathlib import Path
import re
import sys

version, artifacts, output = sys.argv[1:]
if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?", version):
    raise SystemExit("invalid release version")
blocks = []
for os, triples in [
    ("macos", [("arm", "aarch64-apple-darwin"), ("intel", "x86_64-apple-darwin")]),
    ("linux", [("arm", "aarch64-unknown-linux-gnu"), ("intel", "x86_64-unknown-linux-gnu")]),
]:
    lines = [f"  on_{os} do"]
    for arch, target in triples:
        archive = Path(artifacts) / f"edgelord-{target}.tar.gz"
        digest = hashlib.sha256(archive.read_bytes()).hexdigest()
        if archive.with_suffix(".gz.sha256").read_text().split()[0] != digest:
            raise SystemExit(f"checksum mismatch: {archive}")
        lines += [f"    on_{arch} do", f'      url "https://github.com/rdekovich/edgelord/releases/download/v{version}/{archive.name}"', f'      sha256 "{digest}"', "    end"]
    lines += ["  end"]
    blocks.append("\n".join(lines))
Path(output).write_text('''# Generated by scripts/update-formula.py; do not edit checksums by hand.
class Edgelord < Formula
  desc "Prediction market arbitrage detection and execution CLI"
  homepage "https://github.com/rdekovich/edgelord"
  license any_of: ["MIT", "Apache-2.0"]
''' + f'  version "{version}"\n\n' + "\n\n".join(blocks) + '''

  def install
    bin.install "edgelord"
  end

  test do
    assert_match "edgelord", shell_output("#{bin}/edgelord --version")
    system bin/"edgelord", "strategies", "list"
  end
end
''')
